package main

import (
	"encoding/csv"
	"flag"
	"fmt"
	"log"
	"os"
	"strconv"
	"strings"
	"time"
)

const (
	colProtocol = iota
	colOp
	colConcurrency
	colLabel
	colRequests
	colErrors
	colRetries
	colP50
	colP95
	colP99
	colMax
	colRPS
	colSentBytes
	colRecvBytes
)

var header = []string{"protocol", "op", "concurrency", "label", "requests", "errors", "retries",
	"p50_ms", "p95_ms", "p99_ms", "max_ms", "rps", "sent_bytes_per_req", "recv_bytes_per_req"}

func main() {
	in := flag.String("in", "bench/results/results.csv", "CSV with one row per k6 run")
	out := flag.String("out", "bench/results/results.md", "markdown report to write")
	flag.Parse()
	if err := writeReport(*in, *out); err != nil {
		log.Fatal(err)
	}
}

func writeReport(in, out string) error {
	f, err := os.Open(in)
	if err != nil {
		return err
	}
	defer f.Close()
	records, err := csv.NewReader(f).ReadAll()
	if err != nil {
		return fmt.Errorf("read csv: %w", err)
	}
	if len(records) < 2 {
		return fmt.Errorf("%s has no results", in)
	}
	if strings.Join(records[0], ",") != strings.Join(header, ",") {
		return fmt.Errorf("%s: unexpected header %v", in, records[0])
	}

	type key struct{ label, op, conc string }
	byProto := map[key]map[string][]string{}
	var order []key
	var labels []string
	seenLabel := map[string]bool{}
	for _, r := range records[1:] {
		k := key{label: r[colLabel], op: r[colOp], conc: r[colConcurrency]}
		if byProto[k] == nil {
			byProto[k] = map[string][]string{}
			order = append(order, k)
		}
		byProto[k][r[colProtocol]] = r
		if !seenLabel[r[colLabel]] {
			seenLabel[r[colLabel]] = true
			labels = append(labels, r[colLabel])
		}
	}

	var b strings.Builder
	b.WriteString("# Benchmark results: gRPC vs REST/JSON (k6)\n\n")
	fmt.Fprintf(&b, "Generated by `go run ./cmd/benchreport` from `%s` (%s).\n\n", in, time.Now().Format("2006-01-02"))
	b.WriteString("Latency in milliseconds: k6 `iteration_duration`, the full call including retries. " +
		"req/s = VUs × 1000 / mean call time. " +
		"Bytes are k6 `data_sent` / `data_received` per request: everything on the wire, headers and framing included.\n")

	for _, label := range labels {
		fmt.Fprintf(&b, "\n## %s\n\n", label)
		b.WriteString("| op | conc | protocol | p50 | p95 | p99 | max | req/s | sent B/req | recv B/req | errors | retries |\n")
		b.WriteString("|---|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n")
		for _, k := range order {
			if k.label != label {
				continue
			}
			for _, p := range []string{"grpc", "rest"} {
				r, ok := byProto[k][p]
				if !ok {
					continue
				}
				fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n",
					r[colOp], r[colConcurrency], r[colProtocol], r[colP50], r[colP95], r[colP99], r[colMax],
					r[colRPS], r[colSentBytes], r[colRecvBytes], r[colErrors], r[colRetries])
			}
		}

		b.WriteString("\n**REST / gRPC** (how many times larger REST is; >1 means gRPC is better):\n\n")
		b.WriteString("| op | conc | p50 | p99 | req/s (gRPC / REST) | recv bytes |\n|---|---:|---:|---:|---:|---:|\n")
		for _, k := range order {
			g, okG := byProto[k]["grpc"]
			r, okR := byProto[k]["rest"]
			if k.label != label || !okG || !okR {
				continue
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n", k.op, k.conc,
				ratio(r[colP50], g[colP50]), ratio(r[colP99], g[colP99]),
				ratio(g[colRPS], r[colRPS]), ratio(r[colRecvBytes], g[colRecvBytes]))
		}
	}
	return os.WriteFile(out, []byte(b.String()), 0o644)
}

func ratio(a, b string) string {
	x, err1 := strconv.ParseFloat(a, 64)
	y, err2 := strconv.ParseFloat(b, 64)
	if err1 != nil || err2 != nil || y == 0 {
		return "—"
	}
	return strconv.FormatFloat(x/y, 'f', 2, 64) + "×"
}
